"""Generate prometheus/slo-rules.yml (recording + multi-window multi-burn-rate alerts)."""
import pathlib
W = ["5m", "30m", "1h", "2h", "6h", "1d", "3d"]
SLOS = [("availability", "checkout_errors", 0.005), ("latency", "checkout_slow", 0.01)]
# (severity, long window, short window, burn rate, for, % of 30d budget consumed when it fires)
TIERS = [("page", "1h", "5m", 14.4, "2m", "2%"), ("page", "6h", "30m", 6, "15m", "5%"),
         ("ticket", "1d", "2h", 3, "1h", "10%"), ("ticket", "3d", "6h", 1, "3h", "10%")]

def render():
    o = ["# GENERATED by scripts/gen_rules.py - do not edit by hand",
         "# SLO 1: checkout availability 99.5% / 30d  -> error budget 0.005",
         "# SLO 2: checkout latency: 99% of requests < 300ms / 30d -> budget 0.01",
         "# Alerts: multi-window multi-burn-rate (Google SRE Workbook, 'Alerting on SLOs', recipe 6)",
         "groups:", "  - name: slo-recording", "    interval: 15s", "    rules:"]
    for w in W:
        o += [f"      - record: slo:checkout_errors:ratio_rate{w}",
              f"        expr: (sum(rate(http_requests_total{{route=\"/checkout\",code=~\"5..\"}}[{w}])) or vector(0)) / sum(rate(http_requests_total{{route=\"/checkout\"}}[{w}]))",
              f"      - record: slo:checkout_slow:ratio_rate{w}",
              f"        expr: 1 - (sum(rate(http_request_duration_seconds_bucket{{route=\"/checkout\",le=\"0.3\"}}[{w}])) / sum(rate(http_request_duration_seconds_count{{route=\"/checkout\"}}[{w}])))"]
    o += ["  - name: slo-alerts", "    interval: 15s", "    rules:"]
    for slo, metric, budget in SLOS:
        for sev, lw, sw, br, f, pct in TIERS:
            thr = round(br * budget, 6)
            o += [f"      - alert: CheckoutSLO{slo.capitalize()}Burn{lw}",
                  f"        expr: slo:{metric}:ratio_rate{lw} > {thr} and slo:{metric}:ratio_rate{sw} > {thr}",
                  f"        for: {f}",
                  f"        labels: {{severity: {sev}, slo: checkout-{slo}, burn_rate: \"{br}\"}}",
                  "        annotations:",
                  f"          summary: \"checkout {slo} SLO burning {br}x budget ({lw}/{sw} windows)\"",
                  f"          description: \"{lw} ratio={{{{ $value | humanizePercentage }}}} > {thr*100:.3g}%. At {br}x, {pct} of the 30d budget is gone in {lw}.\"",
                  f"          runbook_url: https://github.com/ansarshaikh/slo-lab/blob/main/RUNBOOK.md#{slo}"]
    return "\n".join(o) + "\n"

if __name__ == "__main__":
    pathlib.Path(__file__).resolve().parents[1].joinpath("prometheus/slo-rules.yml").write_text(render())
